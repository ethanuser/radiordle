import { db, isSupabaseConfigured } from './supabase';
import { calculateStatsFromResults } from './statsCalculation';
import type { GameResult, RecoveredStats } from './statsCalculation';

/**
 * Rebuilds a player's statistics from their game_results history.
 * Returns null when there is no history (or the backend is unavailable).
 *
 * Previously served by /api/player-stats; now queried from the browser so the
 * static GitHub Pages build can still recover stats.
 */
export async function fetchPlayerStats(playerHash: string): Promise<RecoveredStats | null> {
  if (!isSupabaseConfigured) return null;

  // Basic format check (hashes are generated by lib/playerIdentity)
  if (!/^[a-z0-9-]+$/i.test(playerHash) || playerHash.length > 50) {
    return null;
  }

  const { data: results, error } = await db()
    .from('game_results')
    .select('puzzle_number, won, guess_count, played_at')
    .eq('player_hash', playerHash)
    .order('played_at', { ascending: true });

  if (error) {
    console.error('Error fetching player stats:', error);
    return null;
  }
  if (!results || results.length === 0) {
    return null;
  }

  // Map puzzle_number -> day_number via puzzle_schedule for streak calculation
  const [{ data: schedules, error: scheduleError }, { data: puzzles, error: puzzleError }] =
    await Promise.all([
      db().from('puzzle_schedule').select('day_number, puzzle_id'),
      db().from('puzzles').select('id, puzzle_number'),
    ]);

  if (scheduleError) console.error('Error fetching puzzle schedule:', scheduleError);
  if (puzzleError) console.error('Error fetching puzzles:', puzzleError);

  const puzzleNumToDayNum: { [key: number]: number } = {};
  if (schedules && puzzles) {
    const puzzleIdToNum: { [key: string]: number } = {};
    for (const p of puzzles) {
      puzzleIdToNum[p.id] = p.puzzle_number;
    }
    for (const s of schedules) {
      if (s.puzzle_id && puzzleIdToNum[s.puzzle_id] !== undefined) {
        puzzleNumToDayNum[puzzleIdToNum[s.puzzle_id]] = s.day_number;
      }
    }
  }

  return calculateStatsFromResults(results as GameResult[], puzzleNumToDayNum);
}
